inline bool matches_ue4ss_profile(const uint8_t* base, size_t available) {
    if (!base || available < sizeof(IMAGE_DOS_HEADER)) return false;
    const auto* dos = reinterpret_cast<const IMAGE_DOS_HEADER*>(base);
    if (dos->e_magic != IMAGE_DOS_SIGNATURE || dos->e_lfanew < 0) return false;
    const size_t nt_offset = static_cast<size_t>(dos->e_lfanew);
    if (nt_offset > available || sizeof(IMAGE_NT_HEADERS64) > available-nt_offset) return false;
    const auto* nt = reinterpret_cast<const IMAGE_NT_HEADERS64*>(base+nt_offset);
    if (nt->Signature != IMAGE_NT_SIGNATURE || nt->OptionalHeader.Magic != IMAGE_NT_OPTIONAL_HDR64_MAGIC ||
        nt->FileHeader.Machine != IMAGE_FILE_MACHINE_AMD64 ||
        nt->FileHeader.TimeDateStamp != expected_timestamp ||
        nt->OptionalHeader.SizeOfImage != expected_size || available < expected_size) return false;
    const auto& dir = nt->OptionalHeader.DataDirectory[IMAGE_DIRECTORY_ENTRY_DEBUG];
    if (!dir.VirtualAddress || dir.VirtualAddress > available || dir.Size > available-dir.VirtualAddress) return false;
    bool identity = false;
    for (size_t pos=0; pos+sizeof(IMAGE_DEBUG_DIRECTORY)<=dir.Size; pos+=sizeof(IMAGE_DEBUG_DIRECTORY)) {
        const auto* debug = reinterpret_cast<const IMAGE_DEBUG_DIRECTORY*>(base+dir.VirtualAddress+pos);
        if (debug->Type != IMAGE_DEBUG_TYPE_CODEVIEW || debug->SizeOfData < 24 ||
            debug->AddressOfRawData > available || 24 > available-debug->AddressOfRawData) continue;
        const auto* cv=base+debug->AddressOfRawData;
        uint32_t age=0; std::memcpy(&age,cv+20,4);
        if (!std::memcmp(cv,"RSDS",4) && !std::memcmp(cv+4,expected_pdb_guid,16) && age==expected_pdb_age) identity=true;
    }
    if (!identity) return false;
    for (const auto& binding:lua_bindings) {
        if (binding.rva > available || 16 > available-binding.rva ||
            std::memcmp(base+binding.rva,binding.entry,16)) return false;
    }
    return true;
}
